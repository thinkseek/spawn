-- The logins from before they were per database (`spawn_supervisor`,
-- `spawn_reader`, `spawn_terminal`, one per cluster) lose everything they
-- were granted here, and act as nobody (spawn_principal). They may still
-- log in, with a password an earlier install set (a fixed one, or one
-- derived from that install's owner password): another database on the
-- cluster may still use them, so only a human drops them.
do $$
declare
    v_role text;
begin
    foreach v_role in array array['spawn_supervisor', 'spawn_reader', 'spawn_terminal'] loop
        if exists (select 1 from pg_roles where rolname = v_role) then
            execute format('revoke all on all tables in schema %I from %I', current_schema(), v_role);
            execute format('revoke all on all sequences in schema %I from %I',
                           current_schema(), v_role);
            execute format('revoke all on all functions in schema %I from %I',
                           current_schema(), v_role);
            execute format('revoke all on schema %I from %I', current_schema(), v_role);
            -- The database's row is the cluster's: written only to take one.
            if exists (select 1 from pg_database d cross join lateral aclexplode(d.datacl) a
                        where d.datname = current_database()
                          and a.grantee = (select oid from pg_roles where rolname = v_role)) then
                execute format('revoke all on database %I from %I', current_database(), v_role);
            end if;
            if exists (select 1 from pg_roles where rolname = v_role and rolcanlogin) then
                raise warning 'role % from an earlier install can still log in; it has no access '
                              'here any more (this database''s logins are %): drop it once no '
                              'other database on the cluster uses it',
                              v_role, spawn_login_role(v_role);
            end if;
        end if;
    end loop;
end
$$;

-- A restricted login of this database: created without login (a migration
-- with the owner's password gives it one, PostgresStore::migrate), with a
-- random salt in its comment that its password derives from, and the right
-- to connect and to see the schema.
do $$
declare
    v_base text;
    v_role text;
begin
    foreach v_base in array array['spawn_supervisor', 'spawn_reader', 'spawn_human'] loop
        v_role := spawn_login_role(v_base);
        if not exists (select 1 from pg_roles where rolname = v_role) then
            execute format('create role %I nologin', v_role);
        end if;
        if coalesce(shobj_description((select oid from pg_roles where rolname = v_role),
                                      'pg_authid'), '') !~ '^spawn login salt [0-9a-f]{64}$' then
            execute format('comment on role %I is %L', v_role,
                           'spawn login salt '
                           || replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''));
        end if;
        -- The database's row is the cluster's too: granted once.
        if not exists (select 1 from pg_database d cross join lateral aclexplode(d.datacl) a
                        where d.datname = current_database() and a.privilege_type = 'CONNECT'
                          and a.grantee = (select oid from pg_roles where rolname = v_role)) then
            execute format('grant connect on database %I to %I', current_database(), v_role);
        end if;
        execute format('grant usage on schema %I to %I', current_schema(), v_role);
    end loop;
end
$$;

-- A migration without the owner's password turns this database's logins
-- off (PostgresStore::migrate): their passwords derive from the owner's, so
-- none can be set, and one an earlier migration set must not outlive it.
create or replace function spawn_logins_off() returns void
language plpgsql as $$
declare
    v_role text;
begin
    foreach v_role in array array[spawn_login_role('spawn_supervisor'),
                                  spawn_login_role('spawn_reader'),
                                  spawn_login_role('spawn_human')] loop
        execute format('alter role %I with nologin password null', v_role);
    end loop;
    raise warning 'the database URL has no owner password: logins %, % and % are off (no login, '
                  'no password) until a migration with the owner''s password',
                  spawn_login_role('spawn_supervisor'), spawn_login_role('spawn_reader'),
                  spawn_login_role('spawn_human');
end $$;
revoke execute on function spawn_logins_off() from public;

