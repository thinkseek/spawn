-- Missions, tasks and residents (docs/fleet-architecture.md §3.2).
--
-- These tables are the fold of the control stream (§10.1 and
-- `spawn_control_apply` below), never written directly. Humans add missions
-- and approve residents; the supervisor decides tasks and reviews reports
-- through the checked functions; the dispatcher records deliveries and
-- reports as the owner.
create table if not exists mission_missions (
    id            bigint generated by default as identity primary key,
    text          text   not null,
    origin        text   not null,
    sources       jsonb  not null default '[]'::jsonb,
    state         text   not null default 'open'
                  check (state in ('open', 'active', 'done', 'dropped')),
    summary       text,
    created_at_ms bigint not null,
    updated_at_ms bigint not null,
    -- Landing (§10.3): a gate (a scenarios directory in the controller's
    -- checkout) lands the tasks' work on the source, after the supervisor's
    -- review (`review`) or on the gate alone (`gate`). `baseline` is where
    -- the last landing left the source's main; `halted` holds the reason a
    -- halt rule fired, until a human resumes the mission.
    gate            text,
    accept          text    not null default 'review' check (accept in ('review', 'gate')),
    budget          jsonb,
    baseline        text,
    halted          text,
    scenario_floor  integer not null default 0,
    gate_rejections integer not null default 0,
    gate_aborts     integer not null default 0,
    -- An objective mission (§10.4): `{"backlog": <dir>, "resident": <name>}`.
    objectives      jsonb
);

create table if not exists mission_residents (
    name          text   primary key check (name ~ '^[a-z][a-z0-9_]{0,30}$'),
    agent_id      text   not null unique,
    session_id    text   not null unique,
    charter       text   not null,
    state         text   not null default 'proposed'
                  check (state in ('proposed', 'approved', 'retired')),
    proposed_by   text   not null,
    approved_by   text,
    created_at_ms bigint not null,
    updated_at_ms bigint not null
);

create table if not exists mission_tasks (
    id            bigint generated by default as identity primary key,
    mission_id    bigint not null references mission_missions (id),
    kind          text   not null check (kind in ('resident', 'ephemeral')),
    agent_id      text   not null,
    session_id    text   not null,
    brief         text   not null,
    state         text   not null default 'assigned'
                  check (state in ('assigned', 'delivered', 'reported', 'revise',
                                   'accepted', 'cancelled', 'landing', 'landed')),
    revisions     integer not null default 0,
    review_note   text,
    command_id    bigint,
    report        text,
    created_by    text   not null,
    created_at_ms bigint not null,
    updated_at_ms bigint not null,
    -- Landing: the commit the gate judged and its base, the gate's log and
    -- metric, and, for an objective task, the objective and its scenario.
    base            text,
    candidate       text,
    gate_log        text,
    metric          text,
    objective       integer,
    scenario        text,
    delivered_at_ms bigint,
    -- The models the task's worker runs on (docs/fleet-architecture.md,
    -- "Engine models"): `default`, or `cheap` for simple, well-specified work.
    model           text   not null default 'default' check (model in ('default', 'cheap'))
);

