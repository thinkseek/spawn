        -- task continues it (`task.assigned` naming `continues`), so the
        -- task leaves flight and counts toward no halt: the mission's
        -- gate_aborts and gate_rejections stay as they were
        -- (docs/fleet-architecture.md §10.4).
        update mission_tasks set state = 'cancelled', review_note = p_record ->> 'reason',
                                 updated_at_ms = p_at
         where id = v_id;
        -- A task that leaves the gate ends its run of `no_room`.
        update mission_missions set gate_room_task = null, gate_room_since_ms = null,
                                    gate_room_last_ms = null, gate_room_waits = 0,
                                    gate_room_escalated = false, updated_at_ms = p_at
         where gate_room_task = v_id;
    when 'task.reported' then
        update mission_tasks set state = 'reported', report = p_record ->> 'report',
                                 updated_at_ms = p_at
         where id = v_id;
    when 'task.reviewed' then
        v_accepted := (p_record ->> 'accepted')::boolean;
        -- A review names the revision of the report it judged; one on another
        -- revision moves nothing (a record from before it named none applies).
        update mission_tasks
           set state = case when v_accepted then 'accepted' else 'revise' end,
               review_note = case when v_accepted then review_note else p_record ->> 'note' end,
               revisions = revisions + case when v_accepted then 0 else 1 end,
               updated_at_ms = p_at
         where id = v_id
           and (p_record ->> 'revision' is null
                or revisions = (p_record ->> 'revision')::integer);
    when 'task.cancelled' then
        -- `by` names who cancelled (spawn_task_cancel_by), read by the
        -- scorecard, not by the fold.
        update mission_tasks set state = 'cancelled', updated_at_ms = p_at where id = v_id;
        -- A task that leaves the gate ends its run of `no_room`.
        update mission_missions set gate_room_task = null, gate_room_since_ms = null,
                                    gate_room_last_ms = null, gate_room_waits = 0,
                                    gate_room_escalated = false, updated_at_ms = p_at
         where gate_room_task = v_id;
    when 'resident.proposed' then
        insert into mission_residents (name, agent_id, session_id, charter, proposed_by,
                                       created_at_ms, updated_at_ms)
        values (p_record ->> 'name', 'agent_resident_' || (p_record ->> 'name'),
                'session_resident_' || (p_record ->> 'name'), p_record ->> 'charter',
                p_record ->> 'proposed_by', p_at, p_at)
        on conflict (name) do update
           set charter = excluded.charter, updated_at_ms = p_at;
    when 'resident.approved' then
        update mission_residents set state = 'approved', approved_by = 'human', updated_at_ms = p_at
         where name = p_record ->> 'name';
    when 'resident.retired' then
        update mission_residents set state = 'retired', updated_at_ms = p_at
         where name = p_record ->> 'name';
        -- Its work that the closure rule does not let go on is dropped.
        update mission_tasks k set state = 'cancelled', updated_at_ms = p_at
          from mission_missions m, mission_residents r
         where m.id = k.mission_id and r.agent_id = k.agent_id
           and r.name = p_record ->> 'name'
           and not spawn_task_may_continue(k.state, m.state, m.gate is not null, r.state);
    when 'host.disk' then
        -- A fact about this host's free disk (spawn loop, crate disk.rs):
        -- read from the log, folded into no table.
        null;
    when 'alert.fired' then
        -- An alert's one occurrence (spawn loop, crate alerts.rs): one row
        -- per key, and a second `fired` for it is refused (also by
        -- `spawn_alert_record`, the writer). A notice never clears.
        if exists (select 1 from spawn_alerts where key = p_record ->> 'key') then
            raise exception 'alert % was already fired', p_record ->> 'key';
        end if;
        insert into spawn_alerts (key, kind, subject, state, notice, text, evidence,
                                  fired_event_id, fired_at_ms)
        values (p_record ->> 'key', p_record ->> 'kind', p_record ->> 'subject',
                case when coalesce((p_record ->> 'notice')::boolean, false)
                     then 'notice' else 'open' end,
                coalesce((p_record ->> 'notice')::boolean, false),
                p_record ->> 'text', coalesce(p_record -> 'evidence', '{}'::jsonb),
                p_event, p_at);
    when 'backup.dumped', 'backup.bundled', 'backup.verified' then
        -- What `spawn backup` did (crate backup.rs): read from the log by the
        -- next run, folded into no table. What a copy holds is in its record
        -- (its events, watermark and sha256), so the drill compares a
        -- restore with the record and not with the live database
        -- (docs/storage.md, "Where state lives").
        null;
    when 'alert.cleared' then
        -- What cleared an alert, once: the row must be open (a notice never
        -- clears, and a cleared alert is cleared at most once).
        if not exists (select 1 from spawn_alerts
                        where key = p_record ->> 'key' and state = 'open') then
            raise exception 'alert % is not open: nothing to clear', p_record ->> 'key';
        end if;
        update spawn_alerts
           set state = 'cleared', cleared_event_id = p_event, cleared_at_ms = p_at,
               cleared_evidence = coalesce(p_record -> 'evidence', '{}'::jsonb)
         where key = p_record ->> 'key';
    when 'task.report_unfinished' then
        -- A report still a draft, not taken (spawn_task_report_unfinished):
        -- the task stays delivered, so nothing is folded.
        null;
    when 'task.fork_failed' then
        -- The dispatcher could not fork an objective task's workspace from
        -- its predecessor's work (spawn_task_fork_failed): read from the
        -- log, folded into no table.
        null;
    when 'source.push_requested' then
        -- The owner asked for a commit on a source's main (`spawn mission
        -- push`): a request the integrator applies between its steps, read
        -- from the log, folded into no table. Its outcome names it: a
        -- `source.moved` (which moves the baselines) or a
        -- `source.push_refused`.
        null;
    when 'source.push_refused' then
        -- The integrator could not apply an owner's request (a conflict, a
        -- commit not in the source, main moving under it twice): main and
        -- every baseline stay where they were.
        null;
    when 'legacy.imported' then
        -- A row from before the control stream, as it was.
        case p_record ->> 'table'
        when 'mission_missions' then
            -- Columns added after the import take their defaults.
            insert into mission_missions
            select * from jsonb_populate_record(null::mission_missions,
                jsonb_build_object('accept', 'review', 'scenario_floor', 0,
                                   'gate_rejections', 0, 'gate_aborts', 0, 'gate_room_waits', 0,
                                   'gate_room_escalated', false, 'gate_host_faults', 0)
                || (p_record -> 'row'));
        when 'mission_residents' then
            insert into mission_residents
            select * from jsonb_populate_record(null::mission_residents, p_record -> 'row');
        when 'mission_tasks' then
            insert into mission_tasks
            select * from jsonb_populate_record(null::mission_tasks,
                jsonb_build_object('model', 'default') || (p_record -> 'row'));
        else
            raise exception 'legacy record of unknown table %', p_record ->> 'table';
        end case;
    else
        raise exception 'unknown control record %', v_type;
    end case;
end $$;

-- Append one record to the control stream and fold it into the tables.
create or replace function spawn_control_record(p_record jsonb)
returns bigint language plpgsql as $$
declare
    v_id bigint;
    v_at bigint;
begin
    select a.out_id, a.out_at into v_id, v_at
      from spawn_append_trusted('agent_control', 'session_control', null, 'control', null,
                                jsonb_build_object('name', 'control.recorded',
                                                   'detail', jsonb_build_object('record', p_record))) a;
    -- A host fault is judged again `backoff_ms` after its own record: its
    -- `due_ms` is the record's time plus that, which only the append knows.
    -- It is written into the record in the transaction that appends it, so
    -- no reader ever sees the record without it.
    if p_record ->> 'type' = 'task.gated' and p_record ->> 'verdict' = 'host_fault'
       and jsonb_typeof(p_record -> 'backoff_ms') = 'number' then
        p_record := p_record || jsonb_build_object(
            'due_ms', v_at + (p_record ->> 'backoff_ms')::numeric::bigint);
        update spawn_events
           set kind = jsonb_set(kind, '{detail,record}', p_record)
         where id = v_id;
    end if;
    -- An owner's hold expires `bound_s` after its own record, the same way.
    if p_record ->> 'type' = 'source.held' and jsonb_typeof(p_record -> 'bound_s') = 'number' then
        p_record := p_record || jsonb_build_object(
            'expires_ms', v_at + (p_record ->> 'bound_s')::numeric::bigint * 1000);
        update spawn_events
           set kind = jsonb_set(kind, '{detail,record}', p_record)
         where id = v_id;
    end if;
    perform spawn_control_apply(p_record, v_at, v_id);
    return v_id;
end $$;

-- Rebuild the tables from the log. Ids come from the records, so the
-- identity sequences stay ahead of every row.
create or replace function spawn_control_refold()
returns void language plpgsql as $$
declare
    v_event record;
begin
    perform pg_advisory_xact_lock(1399957335);
    delete from mission_source_holds;
    delete from spawn_alerts;
    delete from mission_tasks;
    delete from mission_residents;
    delete from mission_missions;
    for v_event in
        select e.id, e.kind -> 'detail' -> 'record' as record, e.recorded_at_ms
          from spawn_events e
         where e.session_id = 'session_control' and e.event_name = 'control.recorded'
         order by e.session_seq
    loop
        perform spawn_control_apply(v_event.record, v_event.recorded_at_ms, v_event.id);
    end loop;
end $$;

-- Whether `p_source` is a mission source Spawn hands to git: an absolute
-- path, an https:// or ssh:// URL, or ssh's `user@host:path`. Nothing that
-- names another transport (`ext::`, `fd::`, `file://`), nothing relative,
-- nothing that begins like an option, no whitespace or control character in
-- a URL. The controller's git also allows only file, https and ssh
-- (GIT_ALLOW_PROTOCOL), so a source stored before this check still reaches
-- no other transport. Mirrors `MissionSource::parse` in spawn-cli.
create or replace function spawn_source_allowed(p_source text)
returns boolean language sql immutable as $$
    select p_source is not null
       and length(p_source) <= 4096
       and (p_source ~ '^/[^[:cntrl:]]*$'
            or p_source ~ '^(https|ssh)://[^-/[:space:][:cntrl:]][^[:space:][:cntrl:]]*$'
            or p_source ~ '^[A-Za-z0-9_][A-Za-z0-9._-]*@[A-Za-z0-9][A-Za-z0-9.-]*:[^-:[:space:][:cntrl:]][^[:space:][:cntrl:]]*$')
$$;

create or replace function spawn_mission_add(p_text text, p_sources jsonb, p_origin text)
returns bigint language plpgsql security definer as $$
declare
    v_caller text := spawn_mission_caller();
    v_id bigint;
    v_source jsonb;
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if v_caller is null then
        raise exception '% may not add missions', session_user using errcode = '42501';
    end if;
    if coalesce(trim(p_text), '') = '' then
        raise exception 'a mission needs text';
    end if;
    if jsonb_typeof(coalesce(p_sources, '[]'::jsonb)) <> 'array' then
        raise exception 'a mission''s sources are a list' using errcode = '22023';
    end if;
    -- Every source is one git runs as the owner: a checked shape, and from
    -- the supervisor only one a human already gave a mission. The supervisor
    -- reads text other agents write; it never introduces a repository.
    for v_source in select value from jsonb_array_elements(coalesce(p_sources, '[]'::jsonb)) loop
        if jsonb_typeof(v_source) <> 'string' or not spawn_source_allowed(v_source #>> '{}') then
            raise exception 'a source is an absolute path or an https:// or ssh:// URL, not %',
                v_source using errcode = '22023';
        end if;
        if v_caller = 'spawn_supervisor' and not exists (
            select 1 from mission_missions
             where origin <> 'spawn_supervisor' and sources @> jsonb_build_array(v_source)) then
            raise exception 'the supervisor names only a source a human gave a mission, not %',
                v_source using errcode = '42501';
        end if;
    end loop;
    v_id := nextval(pg_get_serial_sequence('mission_missions', 'id'));
    perform spawn_control_record(jsonb_build_object(
        'type', 'mission.added', 'id', v_id, 'text', p_text,
        'origin', case when v_caller = 'spawn_supervisor' then 'spawn_supervisor'
                       else coalesce(p_origin, 'human') end,
        'sources', coalesce(p_sources, '[]'::jsonb)));
    return v_id;
end $$;

-- Who cancels, as a `task.cancelled` record names it (`by`): the caller of
-- a checked function, `spawn_supervisor` for the supervisor's login and
-- `human` for the owner's (the CLI; Spawn's loops record their own
-- cancellations under their names: `spawn-integrate`, `spawn-dispatch`).
-- The scorecard tells a person's cancellation from Spawn's by it
-- (docs/design.md §15); a record from before it names none, and counts as
-- a person's.
create or replace function spawn_task_cancel_by() returns text
language sql stable as $$
    select case spawn_mission_caller() when 'spawn_supervisor' then 'spawn_supervisor'
                                       else 'human' end
$$;

-- A close or a retirement cancels, in its fold, the work the closure rule
-- does not let go on. Its writer then gives each task of `p_open` (the ones
-- open before the close) that the fold cancelled its own `task.cancelled`
-- record, so the task's stages end with `cancelled`. The record repeats what
-- the fold did; the fold itself never appends, so replaying the log gives
-- the same tables and adds nothing. Called under the append lock.
-- The record names `by`, the caller (spawn_task_cancel_by).
create or replace function spawn_task_record_cancelled(p_open bigint[])
returns void language plpgsql as $$
declare
    v_task bigint;
begin
    for v_task in
        select id from mission_tasks where id = any(p_open) and state = 'cancelled' order by id
    loop
        perform spawn_control_record(jsonb_build_object('type', 'task.cancelled', 'id', v_task,
                                                        'by', spawn_task_cancel_by()));
    end loop;
end $$;

create or replace function spawn_mission_close(p_mission bigint, p_state text, p_summary text)
returns void language plpgsql security definer as $$
declare
    v_open bigint[];
begin
    -- A drop waits for a landing push in flight (spawn_landing_hold), so
    -- the push cannot land work of a mission dropped meanwhile.
    if p_state = 'dropped' then
        perform pg_advisory_xact_lock(1399957337);
    end if;
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is null then
        raise exception '% may not close missions', session_user using errcode = '42501';
    end if;
    if p_state not in ('done', 'dropped') then
        raise exception 'a mission closes as done or dropped';
    end if;
    if not exists (select 1 from mission_missions where id = p_mission and state in ('open', 'active')) then
        raise exception 'mission % is not open', p_mission;
    end if;
    select coalesce(array_agg(id), '{}') into v_open
      from mission_tasks where mission_id = p_mission and state <> 'cancelled';
    perform spawn_control_record(jsonb_build_object(
        'type', 'mission.closed', 'id', p_mission, 'state', p_state, 'summary', p_summary));
    perform spawn_task_record_cancelled(v_open);
end $$;

-- Assign one task. A resident must be approved; an ephemeral worker gets a
-- new agent named after the label and the task, used for this task only.
-- `p_model` is the profile the worker runs the task on.
drop function if exists spawn_task_assign(bigint, text, text, text);
create or replace function spawn_task_assign(p_mission bigint, p_kind text, p_worker text,
                                             p_brief text, p_model text default 'default')
returns bigint language plpgsql security definer as $$
declare
    v_caller text := spawn_mission_caller();
    v_id bigint;
    v_agent text;
    v_session text;
    v_label text;
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if v_caller is null then
        raise exception '% may not assign tasks', session_user using errcode = '42501';
    end if;
    if not exists (select 1 from mission_missions where id = p_mission and state in ('open', 'active')) then
        raise exception 'mission % is not open', p_mission;
    end if;
    if coalesce(trim(p_brief), '') = '' then
        raise exception 'a task needs a brief';
    end if;
    if p_model is null or p_model not in ('default', 'cheap') then
        raise exception 'a task runs on the default or cheap model profile, not %', p_model;
    end if;
    if p_kind = 'resident' then
        select agent_id, session_id into v_agent, v_session
          from mission_residents where name = p_worker and state = 'approved';
        if v_agent is null then
            raise exception 'resident % is not approved', p_worker;
        end if;
        v_id := nextval(pg_get_serial_sequence('mission_tasks', 'id'));
    elsif p_kind = 'ephemeral' then
        v_id := nextval(pg_get_serial_sequence('mission_tasks', 'id'));
        v_label := left(regexp_replace(lower(coalesce(p_worker, 'task')), '[^a-z0-9]+', '_', 'g'), 20);
        v_label := trim(both '_' from v_label);
        if v_label = '' then v_label := 'task'; end if;
        v_agent := format('agent_worker_%s_%s', v_label, v_id);
        v_session := format('session_worker_%s_%s', v_label, v_id);
    else
        raise exception 'a task is resident or ephemeral, not %', p_kind;
    end if;
    perform spawn_control_record(jsonb_build_object(
        'type', 'task.assigned', 'id', v_id, 'mission_id', p_mission, 'kind', p_kind,
        'agent_id', v_agent, 'session_id', v_session, 'brief', p_brief, 'model', p_model,
        'created_by', case when v_caller = 'owner' then 'human' else v_caller end));
    return v_id;
end $$;

-- The dispatcher's bookkeeping, owner only: a task's delivery command was
-- submitted; a delivered task's report arrived. False when the task is not
-- in the state the step needs, and then nothing is recorded.
create or replace function spawn_task_delivered(p_task bigint, p_command bigint)
returns boolean language plpgsql security definer as $$
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception '% may not record deliveries', session_user using errcode = '42501';
    end if;
    -- A task of a closed mission, or of a retired resident, is not
    -- delivered (the closure rule).
    if not exists (select 1 from mission_tasks where id = p_task and state in ('assigned', 'revise'))
       or not spawn_task_may_move(p_task, 'delivered') then
        return false;
    end if;
    perform spawn_control_record(jsonb_build_object(
        'type', 'task.delivered', 'id', p_task, 'command_id', p_command));
    return true;
end $$;

-- Record a report. `p_commit` names the agent's checkpoint the report's
-- turn ended with (its latest `artifact.committed` when the turn's end was
-- recorded): the integrator judges the report against it, never against an
-- older checkpoint. Null only when the agent has no checkpoint at all; the
-- first version took none, and still records a null commit.
create or replace function spawn_task_reported(p_task bigint, p_report text, p_commit text)
returns boolean language plpgsql security definer as $$
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception '% may not record reports', session_user using errcode = '42501';
    end if;
    -- A report of work the closure rule dropped is not taken.
    if not exists (select 1 from mission_tasks where id = p_task and state = 'delivered')
       or not spawn_task_may_move(p_task, 'reported') then
        return false;
    end if;
    perform spawn_control_record(jsonb_build_object(
        'type', 'task.reported', 'id', p_task, 'report', p_report, 'commit', p_commit));
    return true;
end $$;

create or replace function spawn_task_reported(p_task bigint, p_report text)
returns boolean language plpgsql security definer as $$
begin
    return spawn_task_reported(p_task, p_report, null);
end $$;

-- Whether a report of `p_task` whose content has digest `p_digest` was
-- already found unfinished for the task's current revision (its
-- `task.report_unfinished` record): its worker was told, once, for that
-- content.
create or replace function spawn_task_report_unfinished_recorded(p_task bigint, p_digest text)
returns boolean language sql stable security definer as $$
    select exists (
        select 1
          from spawn_events e
          join mission_tasks k on k.id = p_task
         where e.session_id = 'session_control' and e.event_name = 'control.recorded'
           and e.kind -> 'detail' -> 'record' ->> 'type' = 'task.report_unfinished'
           and e.kind -> 'detail' -> 'record' ->> 'id' = p_task::text
           and e.kind -> 'detail' -> 'record' ->> 'digest' = p_digest
           and (e.kind -> 'detail' -> 'record' ->> 'revision')::integer = k.revisions)
$$;

-- Record that a delivered task's report was read and not taken: it is still
-- a draft (crates/spawn-cli/src/deliver/unfinished.rs). The record names the
-- task's revision, the content's `digest`, the `markers` found (each with
-- its line) and the note that tells the worker (`note`, its idempotency key,
-- and `command_id`). Once per revision and content: false, and nothing
-- recorded, when that content was recorded already, or the task is not
-- delivered. The task stays delivered.
create or replace function spawn_task_report_unfinished(p_task bigint, p_digest text,
                                                        p_markers jsonb, p_note text,
                                                        p_command bigint)
returns boolean language plpgsql security definer as $$
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception '% may not record reports', session_user using errcode = '42501';
    end if;
    if not exists (select 1 from mission_tasks where id = p_task and state = 'delivered')
       or spawn_task_report_unfinished_recorded(p_task, p_digest) then
        return false;
    end if;
    perform spawn_control_record(jsonb_build_object(
        'type', 'task.report_unfinished', 'id', p_task,
        'revision', (select revisions from mission_tasks where id = p_task),
        'digest', p_digest, 'markers', p_markers, 'note', p_note, 'command_id', p_command));
    return true;
end $$;

-- The dispatcher's fork of an assigned objective task's workspace from its
-- predecessor's work failed (crates/spawn-cli/src/main_merge.rs
-- `fork_from_prior`). Recorded once per task, the first failure's error,
-- the predecessor and its commit; returns how long ago that first failure
-- was recorded (ms, the database's clock), from which the dispatcher stops
-- holding the task's Start and starts it without the fork. A task that is
-- not assigned records nothing (null).
create or replace function spawn_task_fork_failed(p_task bigint, p_from bigint, p_commit text,
                                                  p_error text)
returns bigint language plpgsql security definer as $$
declare
    v_first bigint;
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception '% may not record forks', session_user using errcode = '42501';
    end if;
    if not exists (select 1 from mission_tasks where id = p_task and state = 'assigned') then
        return null;
    end if;
    select min(e.recorded_at_ms) into v_first
      from spawn_events e
     where e.session_id = 'session_control' and e.event_name = 'control.recorded'
       and e.kind -> 'detail' -> 'record' ->> 'id' = p_task::text
       and e.kind -> 'detail' -> 'record' ->> 'type' = 'task.fork_failed';
    if v_first is null then
        perform spawn_control_record(jsonb_build_object(
            'type', 'task.fork_failed', 'id', p_task, 'from', p_from, 'commit', p_commit,
            'error', p_error));
        return 0;
    end if;
    return spawn_now_ms() - v_first;
end $$;

-- Review a report: accept, or send it back with a note. `p_revision` names
-- the revision of the report the reviewer read (`revisions` in the news and
-- the board); a review of another revision is refused, so a decision on an
-- old report never lands on a newer one. Without it, the report as it is
-- now (a human at the command line); the record names that revision either
-- way. A mission whose gate alone accepts takes no review: its gate is
-- judging the report, and a review would send back the revision it judges.
-- The first version named no revision.
