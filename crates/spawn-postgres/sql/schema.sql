-- Spawn storage: event log, command queue, read views.
--
-- Times are Unix epoch milliseconds in bigint, so no client date library is
-- needed. Every append takes one transaction-level advisory lock: it makes
-- "id order equals commit order" true, which lets a global reader store its
-- last position and never skip an event.

-- A connection whose search_path names a schema that does not exist yet
-- (an isolated test run) gets it created, so everything below lands there.
do $$
declare
    v_first text := trim(both ' "' from split_part(current_setting('search_path'), ',', 1));
begin
    if current_schema() is null and v_first <> '' and v_first not like '%$user%' then
        execute format('create schema if not exists %I', v_first);
    end if;
end
$$;

create or replace function spawn_now_ms() returns bigint
language sql volatile as $$
    select (extract(epoch from clock_timestamp()) * 1000)::bigint
$$;

create table if not exists spawn_events (
    id              bigint generated by default as identity primary key,
    agent_id        text   not null,
    session_id      text   not null,
    execution_id    text,
    source          text   not null,
    source_event_id text,
    kind            jsonb  not null,
    session_seq     bigint not null,
    recorded_at_ms  bigint not null,
    event_name      text generated always as (kind ->> 'name') stored
);

create unique index if not exists spawn_events_session_seq
    on spawn_events (session_id, session_seq);

create unique index if not exists spawn_events_source_key
    on spawn_events (session_id, source, source_event_id)
    where source_event_id is not null;

create index if not exists spawn_events_session_name
    on spawn_events (session_id, event_name, id);

-- Projection: one row per session, written by `spawn_append` in the same
-- transaction as the event, so `agent_state`, `agent_status` and
-- `agent_freshness` read one row instead of folding the log. The log stays
-- the only truth: a row is the fold of its session's events, and any row
-- out of step with the log is folded again.
create table if not exists spawn_session_state (
    session_id           text   primary key,
    agent_id             text   not null,
    last_session_seq     bigint not null,
    last_event_id        bigint not null,
    last_event_at_ms     bigint not null,
    event_count          bigint not null,
    observation          jsonb,
    observation_seq      bigint,
    observation_event_id bigint,
    observation_at_ms    bigint
);

-- The session belongs to the agent of its first event, so a command another
-- agent submits into the session cannot move it out of its owner's grants.
create or replace function spawn_session_fold(p_session text) returns void
language sql as $$
    insert into spawn_session_state
    select f.session_id, a.agent_id, f.last_session_seq, f.last_event_id,
           f.last_event_at_ms, f.event_count,
           o.observation, o.session_seq, o.id, o.recorded_at_ms
    from (
        select e.session_id,
               max(e.session_seq) as last_session_seq, max(e.id) as last_event_id,
               max(e.recorded_at_ms) as last_event_at_ms, count(*) as event_count
        from spawn_events e
        -- The control stream belongs to no agent (§10.1).
        where e.session_id = p_session and p_session <> 'session_control'
        group by e.session_id
    ) f
    cross join lateral (
        select e.agent_id from spawn_events e
        where e.session_id = f.session_id
        order by e.session_seq limit 1
    ) a
    left join lateral (
        select e.kind -> 'detail' -> 'observation' as observation,
               e.session_seq, e.id, e.recorded_at_ms
        from spawn_events e
        where e.session_id = f.session_id and e.event_name = 'observation.recorded'
        order by e.session_seq desc
        limit 1
    ) o on true
    on conflict (session_id) do update set
        agent_id             = excluded.agent_id,
        last_session_seq     = excluded.last_session_seq,
        last_event_id        = excluded.last_event_id,
        last_event_at_ms     = excluded.last_event_at_ms,
        event_count          = excluded.event_count,
        observation          = excluded.observation,
        observation_seq      = excluded.observation_seq,
        observation_event_id = excluded.observation_event_id,
        observation_at_ms    = excluded.observation_at_ms;
$$;

-- Fold the sessions the projection is missing or behind on: a database from
-- before the projection, or events an older `spawn_append` wrote while this
-- migration ran. The append lock waits for those calls to commit; the
-- migration holds it until its own commit, after which the new body runs.
-- ponytail: this groups the whole log on every migration; keep a migration
-- version and run it once when init-db on a large log gets slow.
select pg_advisory_xact_lock(1399957335);
select spawn_session_fold(f.session_id)
from (select e.session_id, max(e.session_seq) as last_seq
      from spawn_events e group by e.session_id) f
left join spawn_session_state p on p.session_id = f.session_id
where p.last_session_seq is distinct from f.last_seq;

-- The writer. Only the owner reaches it: directly, or through SECURITY
-- DEFINER paths such as the `agent_commands` gateway, which must record
-- `command.accepted` with source `gateway` even when a restricted login
-- submitted the command. Restricted logins call `spawn_append` below.
create or replace function spawn_append_trusted(
    p_agent      text,
    p_session    text,
    p_execution  text,
    p_source     text,
    p_source_key text,
    p_kind       jsonb
) returns table (
    out_id       bigint,
    out_seq      bigint,
    out_at       bigint,
    out_inserted boolean
) language plpgsql security definer as $$
declare
    v_seq bigint;
    v_id  bigint;
    v_at  bigint;
    -- Only the Observer's judgement is the projected state.
    v_obs constant boolean := p_kind ->> 'name' = 'observation.recorded' and p_source = 'observer';
begin
    perform pg_advisory_xact_lock(1399957335);

    if p_source_key is not null and exists (
        select 1 from spawn_events e
        where e.session_id = p_session
          and e.source = p_source
          and e.source_event_id = p_source_key
    ) then
        return query
            select e.id, e.session_seq, e.recorded_at_ms, false
            from spawn_events e
            where e.session_id = p_session
              and e.source = p_source
              and e.source_event_id = p_source_key
            limit 1;
        return;
    end if;

    select coalesce(max(e.session_seq), 0) + 1 into v_seq
        from spawn_events e
        where e.session_id = p_session;

    v_at := spawn_now_ms();

    insert into spawn_events
        (agent_id, session_id, execution_id, source, source_event_id, kind, session_seq, recorded_at_ms)
    values
        (p_agent, p_session, p_execution, p_source, p_source_key, p_kind, v_seq, v_at)
    returning spawn_events.id into v_id;

    -- Guard: step the row only when it holds exactly the previous event.
    -- Any other row (missing, behind, ahead) is folded again from the log.
    update spawn_session_state p set
        last_session_seq     = v_seq,
        last_event_id        = v_id,
        last_event_at_ms     = greatest(p.last_event_at_ms, v_at),
        event_count          = p.event_count + 1,
        observation          = case when v_obs then p_kind -> 'detail' -> 'observation' else p.observation end,
        observation_seq      = case when v_obs then v_seq else p.observation_seq end,
        observation_event_id = case when v_obs then v_id else p.observation_event_id end,
        observation_at_ms    = case when v_obs then v_at else p.observation_at_ms end
    where p.session_id = p_session and p.last_session_seq = v_seq - 1;
    if not found then
        perform spawn_session_fold(p_session);
    end if;

    perform pg_notify('spawn_events', v_id::text);

    return query select v_id, v_seq, v_at, true;
end $$;

-- The entry point for every caller. The agent's terminal (`spawn_terminal`)
-- and the supervisor's (`spawn_supervisor`) own nothing and reach only this
-- function. They may write engine output, never the controller's own facts:
-- a forged `observation.recorded` would let an agent report a state it is not
-- in, and a forged `command.accepted` would confuse the queue's views.
-- `session_user` survives SECURITY DEFINER, so it names the real caller.
create or replace function spawn_append(
    p_agent      text,
    p_session    text,
    p_execution  text,
    p_source     text,
    p_source_key text,
    p_kind       jsonb
) returns table (
    out_id       bigint,
    out_seq      bigint,
    out_at       bigint,
    out_inserted boolean
) language plpgsql security definer as $$
begin
    if session_user in ('spawn_terminal', 'spawn_supervisor') then
        if p_source is distinct from 'claude' and p_source is distinct from 'codex' then
            raise exception '% may not write source %', session_user, p_source
                using errcode = '42501';
        end if;
        -- Engine output only, by name. The runner in the pane reports its own
        -- exit (`execution.ended`, cause `exited`); any other end, and every
        -- controller fact, belongs to the Bridge, the Observer or the gateway.
        -- An unknown name is refused too: one undecodable row would stop
        -- every reader of the closed EventKind.
        if (p_kind ->> 'name') is null or (p_kind ->> 'name') not in (
                'session.native_started', 'session.native_ended', 'message.received',
                'notification.received', 'tool.started', 'tool.completed', 'tool.failed',
                'turn.stopped', 'turn.failed', 'execution.ended')
            or ((p_kind ->> 'name') = 'execution.ended'
                and (p_kind -> 'detail' ->> 'cause') is distinct from 'exited')
        then
            raise exception '% may not write %', session_user, coalesce(p_kind ->> 'name', 'an unnamed event')
                using errcode = '42501';
        end if;
    end if;
    return query
        select * from spawn_append_trusted(p_agent, p_session, p_execution, p_source, p_source_key, p_kind);
end $$;

create table if not exists spawn_commands (
    id              bigint generated by default as identity primary key,
    principal       text   not null,
    idempotency_key text   not null,
    agent_id        text   not null,
    session_id      text   not null,
    action          jsonb  not null,
    state           text   not null default 'pending',
    lease_worker    text,
    lease_attempt   integer not null default 0,
    lease_until_ms  bigint,
    succeeded       boolean,
    error           text,
    created_at_ms   bigint not null,
    finished_at_ms  bigint,
    unique (principal, idempotency_key)
);

create index if not exists spawn_commands_open
    on spawn_commands (session_id, id)
    where state <> 'finished';

create table if not exists spawn_grants (
    principal text not null,
    agent_id  text not null,
    primary key (principal, agent_id)
);

-- A grant either lets a principal read an agent's views (`read`) or also
-- submit commands for it (`all`). `agent_id` is an id, `*`, or a prefix
-- pattern such as `agent_worker_*`, so the supervisor can command every worker
-- without being able to command the RSI agent or itself.
alter table spawn_grants add column if not exists scope text not null default 'all';

create or replace function spawn_grant_matches(p_pattern text, p_agent text)
returns boolean language sql immutable as $$
    select p_pattern = '*'
        or p_pattern = p_agent
        or (right(p_pattern, 1) = '*'
            and left(p_agent, length(p_pattern) - 1) = left(p_pattern, length(p_pattern) - 1))
$$;

create or replace function spawn_submit(
    p_principal text,
    p_key       text,
    p_agent     text,
    p_session   text,
    p_action    jsonb
) returns table (out_id bigint) language plpgsql as $$
declare
    v_id bigint;
begin
    insert into spawn_commands
        (principal, idempotency_key, agent_id, session_id, action, state, created_at_ms)
    values
        (p_principal, p_key, p_agent, p_session, p_action, 'pending', spawn_now_ms())
    on conflict (principal, idempotency_key) do nothing
    returning spawn_commands.id into v_id;

    if v_id is null then
        select c.id into v_id
            from spawn_commands c
            where c.principal = p_principal and c.idempotency_key = p_key;
        return query select v_id;
        return;
    end if;

    perform spawn_append_trusted(
        p_agent, p_session, null, 'gateway', 'cmd_' || v_id || ':accepted',
        jsonb_build_object('name', 'command.accepted',
                           'detail', jsonb_build_object('command_id', v_id)));

    return query select v_id;
end $$;

create or replace function spawn_claim(
    p_worker text,
    p_ttl_ms bigint
) returns table (
    out_id      bigint,
    out_attempt integer,
    out_agent   text,
    out_session text,
    out_action  jsonb
) language sql as $$
    with candidate as (
        select c.id
        from spawn_commands c
        where c.state <> 'finished'
          and (c.lease_until_ms is null or c.lease_until_ms <= spawn_now_ms())
          and not exists (
              select 1 from spawn_commands o
              where o.session_id = c.session_id
                and o.state <> 'finished'
                and o.id < c.id
          )
        order by c.id
        for update skip locked
        limit 1
    )
    update spawn_commands c
    set lease_worker = p_worker,
        lease_attempt = c.lease_attempt + 1,
        lease_until_ms = spawn_now_ms() + p_ttl_ms
    from candidate
    where c.id = candidate.id
    returning c.id, c.lease_attempt, c.agent_id, c.session_id, c.action;
$$;

create or replace function spawn_finish(
    p_command   bigint,
    p_attempt   integer,
    p_succeeded boolean,
    p_error     text
) returns text language plpgsql as $$
declare
    v_state   text;
    v_attempt integer;
    v_agent   text;
    v_session text;
begin
    select c.state, c.lease_attempt, c.agent_id, c.session_id
        into v_state, v_attempt, v_agent, v_session
        from spawn_commands c
        where c.id = p_command
        for update;

    if v_state is null then
        return 'missing';
    end if;
    if v_state = 'finished' then
        return 'already';
    end if;
    if v_attempt <> p_attempt then
        return 'stale';
    end if;

    update spawn_commands c
        set state = 'finished',
            succeeded = p_succeeded,
            error = p_error,
            finished_at_ms = spawn_now_ms()
        where c.id = p_command;

    perform spawn_append(
        v_agent, v_session, null, 'gateway', 'cmd_' || p_command || ':finished',
        jsonb_build_object('name', 'command.finished',
            'detail', jsonb_build_object(
                'command_id', p_command,
                'succeeded', p_succeeded,
                'error', p_error)));

    return 'done';
end $$;

create or replace view agent_commands as
select c.id, c.agent_id, c.session_id, c.idempotency_key, c.action, c.created_at_ms
from spawn_commands c;

create or replace function spawn_gateway_insert() returns trigger
language plpgsql security definer as $$
declare
    v_id bigint;
begin
    if not exists (
        select 1 from spawn_grants g
        where g.principal = session_user::text
          and g.scope = 'all'
          and spawn_grant_matches(g.agent_id, new.agent_id)
    ) then
        raise exception 'principal % has no grant for agent %', session_user, new.agent_id
            using errcode = '42501';
    end if;
    -- A session belongs to the agent that first used it: a grant for one
    -- agent must not reach another agent's session (the Bridge acts on the
    -- session, not the agent).
    if exists (select 1 from spawn_session_state p
                where p.session_id = new.session_id and p.agent_id <> new.agent_id)
       or exists (select 1 from spawn_commands c
                   where c.session_id = new.session_id and c.agent_id <> new.agent_id) then
        raise exception 'session % belongs to another agent than %', new.session_id, new.agent_id
            using errcode = '42501';
    end if;

    select s.out_id into v_id
        from spawn_submit(session_user::text, new.idempotency_key, new.agent_id, new.session_id, new.action) s;

    new.id := v_id;
    select c.created_at_ms into new.created_at_ms from spawn_commands c where c.id = v_id;
    return new;
end $$;

drop trigger if exists spawn_gateway_insert on agent_commands;
create trigger spawn_gateway_insert
    instead of insert on agent_commands
    for each row execute function spawn_gateway_insert();

create or replace view agent_state as
select
    p.session_id,
    p.agent_id,
    p.observation ->> 'state'      as state,
    p.observation ->> 'reason'     as reason,
    (p.observation ->> 'confidence')::float8 as confidence,
    (p.observation ->> 'based_on_seq')::bigint as based_on_seq,
    p.observation ->> 'judge'      as judge,
    p.observation_seq as session_seq,
    p.observation_at_ms as recorded_at_ms,
    p.observation_event_id as event_id,
    p.observation
from spawn_session_state p
where p.observation is not null;

