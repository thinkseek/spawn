-- Who may call the mission functions: the owner (humans' CLI, the
-- controller) and the supervisor's login.
create or replace function spawn_mission_caller() returns text
language sql stable as $$
    select case when session_user = 'spawn_supervisor' then 'spawn_supervisor'
                when session_user in ('spawn_terminal', 'spawn_reader') then null
                else 'owner' end
$$;

-- The control stream (docs/fleet-architecture.md §10.1). Every change to a
-- mission, task or resident is one `control.recorded` event of session
-- `session_control`; the `mission_*` tables are its fold, written only by
-- `spawn_control_apply`, in the same transaction as the event. The checked
-- functions below validate against the tables, then record. Applying a
-- record never validates: the log is the truth, and replaying it must give
-- the same tables.
create or replace function spawn_control_apply(p_record jsonb, p_at bigint)
returns void language plpgsql as $$
declare
    v_type text := p_record ->> 'type';
    v_id bigint := (p_record ->> 'id')::bigint;
    v_accepted boolean;
    v_verdict text;
    v_mission bigint;
    v_accept text;
begin
    case v_type
    when 'mission.added' then
        insert into mission_missions (id, text, origin, sources, created_at_ms, updated_at_ms)
        values (v_id, p_record ->> 'text', p_record ->> 'origin',
                coalesce(p_record -> 'sources', '[]'::jsonb), p_at, p_at);
    when 'mission.closed' then
        update mission_missions set state = p_record ->> 'state', summary = p_record ->> 'summary',
                                    updated_at_ms = p_at
         where id = v_id;
        -- Work still queued for a closed mission is dropped. Accepted work
        -- of a gated mission, and work the gate passed (landing), still
        -- lands when the mission is done, and is dropped with the mission
        -- otherwise.
        update mission_tasks set state = 'cancelled', updated_at_ms = p_at
         where mission_id = v_id
           and (state in ('assigned', 'revise')
                or (p_record ->> 'state' = 'dropped'
                    and (state = 'landing'
                         or (state = 'accepted'
                             and exists (select 1 from mission_missions m
                                          where m.id = v_id and m.gate is not null)))));
    when 'task.assigned' then
        insert into mission_tasks (id, mission_id, kind, agent_id, session_id, brief,
                                   created_by, objective, scenario, model,
                                   created_at_ms, updated_at_ms)
        values (v_id, (p_record ->> 'mission_id')::bigint, p_record ->> 'kind',
                p_record ->> 'agent_id', p_record ->> 'session_id', p_record ->> 'brief',
                p_record ->> 'created_by', (p_record ->> 'objective')::integer,
                p_record ->> 'scenario', coalesce(p_record ->> 'model', 'default'), p_at, p_at);
        update mission_missions set state = 'active', updated_at_ms = p_at
         where id = (p_record ->> 'mission_id')::bigint and state = 'open';
    when 'mission.configured' then
        update mission_missions set gate = p_record ->> 'gate', accept = p_record ->> 'accept',
                                    budget = p_record -> 'budget',
                                    objectives = p_record -> 'objectives', updated_at_ms = p_at
         where id = v_id;
    when 'mission.halted' then
        update mission_missions set halted = p_record ->> 'reason', updated_at_ms = p_at
         where id = v_id;
    when 'mission.resumed' then
        -- The next gate records the source's main as the new baseline, and
        -- the scenario count as the new floor: a human who resumes has seen
        -- the scenarios as they are (only the owner changes them).
        update mission_missions set halted = null, baseline = null, gate_rejections = 0,
                                    gate_aborts = 0, scenario_floor = 0, updated_at_ms = p_at
         where id = v_id;
    when 'source.moved' then
        -- The owner moved a source's main on purpose (a deploy), forward from
        -- where the last landing left it: the missions on that source take
        -- the new main as their baseline instead of halting at the next pass.
        update mission_missions set baseline = p_record ->> 'to', updated_at_ms = p_at
         where sources ->> 0 = p_record ->> 'source' and baseline = p_record ->> 'from';
    when 'task.delivered' then
        update mission_tasks set state = 'delivered', command_id = (p_record ->> 'command_id')::bigint,
                                 delivered_at_ms = p_at, updated_at_ms = p_at
         where id = v_id;
    when 'task.gated' then
        v_verdict := p_record ->> 'verdict';
        select k.mission_id, m.accept into v_mission, v_accept
          from mission_tasks k join mission_missions m on m.id = k.mission_id
         where k.id = v_id;
        update mission_tasks
           set state = case v_verdict
                         when 'accepted' then 'landing'
                         when 'rejected' then 'revise'
                         when 'conflict' then 'revise'
                         when 'stale' then case when v_accept = 'gate' then 'reported' else 'accepted' end
                         else state end,
               base = coalesce(p_record ->> 'base', base),
               candidate = case when v_verdict = 'accepted' then p_record ->> 'candidate'
                                when v_verdict = 'aborted' then candidate end,
               gate_log = coalesce(p_record ->> 'log', gate_log),
               metric = case when v_verdict = 'accepted' then p_record ->> 'metric' else metric end,
               review_note = case when v_verdict in ('rejected', 'conflict') then p_record ->> 'note'
                                  else review_note end,
               revisions = revisions + case when v_verdict in ('rejected', 'conflict') then 1 else 0 end,
               updated_at_ms = p_at
         where id = v_id;
        update mission_missions
           set baseline = coalesce(baseline, p_record ->> 'base'),
               gate_rejections = case v_verdict when 'rejected' then gate_rejections + 1
                                                when 'accepted' then 0 else gate_rejections end,
               gate_aborts = case v_verdict when 'aborted' then gate_aborts + 1
                                            when 'stale' then gate_aborts
                                            else 0 end,
               scenario_floor = greatest(scenario_floor, coalesce((p_record ->> 'scenarios')::integer, 0)),
               updated_at_ms = p_at
         where id = v_mission;
    when 'task.landed' then
        update mission_tasks set state = 'landed', updated_at_ms = p_at where id = v_id;
        -- Every mission on the same source sees the same main: the landing
        -- moves the baseline of each one that has one.
        update mission_missions m set baseline = p_record ->> 'to', updated_at_ms = p_at
          from mission_missions own join mission_tasks k on k.mission_id = own.id
         where k.id = v_id
           and (m.id = own.id
                or (m.baseline is not null and m.sources ->> 0 = own.sources ->> 0));
    when 'task.aborted' then
        -- Over budget: the work is dropped, and it counts toward the abort halt.
        update mission_tasks set state = 'cancelled', review_note = p_record ->> 'reason',
                                 updated_at_ms = p_at
         where id = v_id;
        update mission_missions set gate_aborts = gate_aborts + 1, updated_at_ms = p_at
         where id = (select mission_id from mission_tasks where id = v_id);
    when 'task.reported' then
        update mission_tasks set state = 'reported', report = p_record ->> 'report',
                                 updated_at_ms = p_at
         where id = v_id;
    when 'task.reviewed' then
        v_accepted := (p_record ->> 'accepted')::boolean;
        update mission_tasks
           set state = case when v_accepted then 'accepted' else 'revise' end,
               review_note = case when v_accepted then review_note else p_record ->> 'note' end,
               revisions = revisions + case when v_accepted then 0 else 1 end,
               updated_at_ms = p_at
         where id = v_id;
    when 'task.cancelled' then
        update mission_tasks set state = 'cancelled', updated_at_ms = p_at where id = v_id;
    when 'resident.proposed' then
        insert into mission_residents (name, agent_id, session_id, charter, proposed_by,
                                       created_at_ms, updated_at_ms)
        values (p_record ->> 'name', 'agent_resident_' || (p_record ->> 'name'),
                'session_resident_' || (p_record ->> 'name'), p_record ->> 'charter',
                p_record ->> 'proposed_by', p_at, p_at)
        on conflict (name) do update
           set charter = excluded.charter, updated_at_ms = p_at;
    when 'resident.approved' then
        update mission_residents set state = 'approved', approved_by = 'human', updated_at_ms = p_at
         where name = p_record ->> 'name';
    when 'resident.retired' then
        update mission_residents set state = 'retired', updated_at_ms = p_at
         where name = p_record ->> 'name';
        -- Its queued tasks are dropped.
        update mission_tasks set state = 'cancelled', updated_at_ms = p_at
         where agent_id = 'agent_resident_' || (p_record ->> 'name') and state in ('assigned', 'revise');
    when 'legacy.imported' then
        -- A row from before the control stream, as it was.
        case p_record ->> 'table'
        when 'mission_missions' then
            -- Columns added after the import take their defaults.
            insert into mission_missions
            select * from jsonb_populate_record(null::mission_missions,
                jsonb_build_object('accept', 'review', 'scenario_floor', 0,
                                   'gate_rejections', 0, 'gate_aborts', 0) || (p_record -> 'row'));
        when 'mission_residents' then
            insert into mission_residents
            select * from jsonb_populate_record(null::mission_residents, p_record -> 'row');
        when 'mission_tasks' then
            insert into mission_tasks
            select * from jsonb_populate_record(null::mission_tasks,
                jsonb_build_object('model', 'default') || (p_record -> 'row'));
        else
            raise exception 'legacy record of unknown table %', p_record ->> 'table';
        end case;
    else
        raise exception 'unknown control record %', v_type;
    end case;
end $$;

-- Append one record to the control stream and fold it into the tables.
create or replace function spawn_control_record(p_record jsonb)
returns bigint language plpgsql as $$
declare
    v_id bigint;
    v_at bigint;
begin
    select a.out_id, a.out_at into v_id, v_at
      from spawn_append_trusted('agent_control', 'session_control', null, 'control', null,
                                jsonb_build_object('name', 'control.recorded',
                                                   'detail', jsonb_build_object('record', p_record))) a;
    perform spawn_control_apply(p_record, v_at);
    return v_id;
end $$;

-- Rebuild the tables from the log. Ids come from the records, so the
-- identity sequences stay ahead of every row.
create or replace function spawn_control_refold()
returns void language plpgsql as $$
declare
    v_event record;
begin
    perform pg_advisory_xact_lock(1399957335);
    delete from mission_tasks;
    delete from mission_residents;
    delete from mission_missions;
    for v_event in
        select e.kind -> 'detail' -> 'record' as record, e.recorded_at_ms
          from spawn_events e
         where e.session_id = 'session_control' and e.event_name = 'control.recorded'
         order by e.session_seq
    loop
        perform spawn_control_apply(v_event.record, v_event.recorded_at_ms);
    end loop;
end $$;

create or replace function spawn_mission_add(p_text text, p_sources jsonb, p_origin text)
returns bigint language plpgsql security definer as $$
declare
    v_caller text := spawn_mission_caller();
    v_id bigint;
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if v_caller is null then
        raise exception '% may not add missions', session_user using errcode = '42501';
    end if;
    if coalesce(trim(p_text), '') = '' then
        raise exception 'a mission needs text';
    end if;
    v_id := nextval(pg_get_serial_sequence('mission_missions', 'id'));
    perform spawn_control_record(jsonb_build_object(
        'type', 'mission.added', 'id', v_id, 'text', p_text,
        'origin', case when v_caller = 'spawn_supervisor' then 'spawn_supervisor'
                       else coalesce(p_origin, 'human') end,
        'sources', coalesce(p_sources, '[]'::jsonb)));
    return v_id;
end $$;

create or replace function spawn_mission_close(p_mission bigint, p_state text, p_summary text)
returns void language plpgsql security definer as $$
begin
    -- A drop waits for a landing push in flight (spawn_landing_hold), so
    -- the push cannot land work of a mission dropped meanwhile.
    if p_state = 'dropped' then
        perform pg_advisory_xact_lock(1399957337);
    end if;
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is null then
        raise exception '% may not close missions', session_user using errcode = '42501';
    end if;
    if p_state not in ('done', 'dropped') then
        raise exception 'a mission closes as done or dropped';
    end if;
    if not exists (select 1 from mission_missions where id = p_mission and state in ('open', 'active')) then
        raise exception 'mission % is not open', p_mission;
    end if;
    perform spawn_control_record(jsonb_build_object(
        'type', 'mission.closed', 'id', p_mission, 'state', p_state, 'summary', p_summary));
end $$;

-- Assign one task. A resident must be approved; an ephemeral worker gets a
-- new agent named after the label and the task, used for this task only.
-- `p_model` is the profile the worker runs the task on.
drop function if exists spawn_task_assign(bigint, text, text, text);
create or replace function spawn_task_assign(p_mission bigint, p_kind text, p_worker text,
                                             p_brief text, p_model text default 'default')
returns bigint language plpgsql security definer as $$
declare
    v_caller text := spawn_mission_caller();
    v_id bigint;
    v_agent text;
    v_session text;
    v_label text;
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if v_caller is null then
        raise exception '% may not assign tasks', session_user using errcode = '42501';
    end if;
    if not exists (select 1 from mission_missions where id = p_mission and state in ('open', 'active')) then
        raise exception 'mission % is not open', p_mission;
    end if;
    if coalesce(trim(p_brief), '') = '' then
        raise exception 'a task needs a brief';
    end if;
    if p_model is null or p_model not in ('default', 'cheap') then
        raise exception 'a task runs on the default or cheap model profile, not %', p_model;
    end if;
    if p_kind = 'resident' then
        select agent_id, session_id into v_agent, v_session
          from mission_residents where name = p_worker and state = 'approved';
        if v_agent is null then
            raise exception 'resident % is not approved', p_worker;
        end if;
        v_id := nextval(pg_get_serial_sequence('mission_tasks', 'id'));
    elsif p_kind = 'ephemeral' then
        v_id := nextval(pg_get_serial_sequence('mission_tasks', 'id'));
        v_label := left(regexp_replace(lower(coalesce(p_worker, 'task')), '[^a-z0-9]+', '_', 'g'), 20);
        v_label := trim(both '_' from v_label);
        if v_label = '' then v_label := 'task'; end if;
        v_agent := format('agent_worker_%s_%s', v_label, v_id);
        v_session := format('session_worker_%s_%s', v_label, v_id);
    else
        raise exception 'a task is resident or ephemeral, not %', p_kind;
    end if;
    perform spawn_control_record(jsonb_build_object(
        'type', 'task.assigned', 'id', v_id, 'mission_id', p_mission, 'kind', p_kind,
        'agent_id', v_agent, 'session_id', v_session, 'brief', p_brief, 'model', p_model,
        'created_by', case when v_caller = 'owner' then 'human' else v_caller end));
    return v_id;
end $$;

