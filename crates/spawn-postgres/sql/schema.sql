-- Spawn storage: event log, command queue, read views.
--
-- Times are Unix epoch milliseconds in bigint, so no client date library is
-- needed. Every append takes one transaction-level advisory lock: it makes
-- "id order equals commit order" true, which lets a global reader store its
-- last position and never skip an event.

create or replace function spawn_now_ms() returns bigint
language sql volatile as $$
    select (extract(epoch from clock_timestamp()) * 1000)::bigint
$$;

create table if not exists spawn_events (
    id              bigint generated by default as identity primary key,
    agent_id        text   not null,
    session_id      text   not null,
    execution_id    text,
    source          text   not null,
    source_event_id text,
    kind            jsonb  not null,
    session_seq     bigint not null,
    recorded_at_ms  bigint not null,
    event_name      text generated always as (kind ->> 'name') stored
);

create unique index if not exists spawn_events_session_seq
    on spawn_events (session_id, session_seq);

create unique index if not exists spawn_events_source_key
    on spawn_events (session_id, source, source_event_id)
    where source_event_id is not null;

create index if not exists spawn_events_session_name
    on spawn_events (session_id, event_name, id);

-- Projection: one row per session, written by `spawn_append` in the same
-- transaction as the event, so `agent_state`, `agent_status` and
-- `agent_freshness` read one row instead of folding the log. The log stays
-- the only truth: a row is the fold of its session's events, and any row
-- out of step with the log is folded again.
create table if not exists spawn_session_state (
    session_id           text   primary key,
    agent_id             text   not null,
    last_session_seq     bigint not null,
    last_event_id        bigint not null,
    last_event_at_ms     bigint not null,
    event_count          bigint not null,
    observation          jsonb,
    observation_seq      bigint,
    observation_event_id bigint,
    observation_at_ms    bigint
);

-- The session belongs to the agent of its first event, so a command another
-- agent submits into the session cannot move it out of its owner's grants.
create or replace function spawn_session_fold(p_session text) returns void
language sql as $$
    insert into spawn_session_state
    select f.session_id, a.agent_id, f.last_session_seq, f.last_event_id,
           f.last_event_at_ms, f.event_count,
           o.observation, o.session_seq, o.id, o.recorded_at_ms
    from (
        select e.session_id,
               max(e.session_seq) as last_session_seq, max(e.id) as last_event_id,
               max(e.recorded_at_ms) as last_event_at_ms, count(*) as event_count
        from spawn_events e
        where e.session_id = p_session
        group by e.session_id
    ) f
    cross join lateral (
        select e.agent_id from spawn_events e
        where e.session_id = f.session_id
        order by e.session_seq limit 1
    ) a
    left join lateral (
        select e.kind -> 'detail' -> 'observation' as observation,
               e.session_seq, e.id, e.recorded_at_ms
        from spawn_events e
        where e.session_id = f.session_id and e.event_name = 'observation.recorded'
        order by e.session_seq desc
        limit 1
    ) o on true
    on conflict (session_id) do update set
        agent_id             = excluded.agent_id,
        last_session_seq     = excluded.last_session_seq,
        last_event_id        = excluded.last_event_id,
        last_event_at_ms     = excluded.last_event_at_ms,
        event_count          = excluded.event_count,
        observation          = excluded.observation,
        observation_seq      = excluded.observation_seq,
        observation_event_id = excluded.observation_event_id,
        observation_at_ms    = excluded.observation_at_ms;
$$;

-- Fold the sessions the projection is missing or behind on: a database from
-- before the projection, or events an older `spawn_append` wrote while this
-- migration ran. The append lock waits for those calls to commit; the
-- migration holds it until its own commit, after which the new body runs.
-- ponytail: this groups the whole log on every migration; keep a migration
-- version and run it once when init-db on a large log gets slow.
select pg_advisory_xact_lock(1399957335);
select spawn_session_fold(f.session_id)
from (select e.session_id, max(e.session_seq) as last_seq
      from spawn_events e group by e.session_id) f
left join spawn_session_state p on p.session_id = f.session_id
where p.last_session_seq is distinct from f.last_seq;

create or replace function spawn_append(
    p_agent      text,
    p_session    text,
    p_execution  text,
    p_source     text,
    p_source_key text,
    p_kind       jsonb
) returns table (
    out_id       bigint,
    out_seq      bigint,
    out_at       bigint,
    out_inserted boolean
) language plpgsql as $$
declare
    v_seq bigint;
    v_id  bigint;
    v_at  bigint;
    v_obs constant boolean := p_kind ->> 'name' = 'observation.recorded';
begin
    perform pg_advisory_xact_lock(1399957335);

    if p_source_key is not null and exists (
        select 1 from spawn_events e
        where e.session_id = p_session
          and e.source = p_source
          and e.source_event_id = p_source_key
    ) then
        return query
            select e.id, e.session_seq, e.recorded_at_ms, false
            from spawn_events e
            where e.session_id = p_session
              and e.source = p_source
              and e.source_event_id = p_source_key
            limit 1;
        return;
    end if;

    select coalesce(max(e.session_seq), 0) + 1 into v_seq
        from spawn_events e
        where e.session_id = p_session;

    v_at := spawn_now_ms();

    insert into spawn_events
        (agent_id, session_id, execution_id, source, source_event_id, kind, session_seq, recorded_at_ms)
    values
        (p_agent, p_session, p_execution, p_source, p_source_key, p_kind, v_seq, v_at)
    returning spawn_events.id into v_id;

    -- Guard: step the row only when it holds exactly the previous event.
    -- Any other row (missing, behind, ahead) is folded again from the log.
    update spawn_session_state p set
        last_session_seq     = v_seq,
        last_event_id        = v_id,
        last_event_at_ms     = greatest(p.last_event_at_ms, v_at),
        event_count          = p.event_count + 1,
        observation          = case when v_obs then p_kind -> 'detail' -> 'observation' else p.observation end,
        observation_seq      = case when v_obs then v_seq else p.observation_seq end,
        observation_event_id = case when v_obs then v_id else p.observation_event_id end,
        observation_at_ms    = case when v_obs then v_at else p.observation_at_ms end
    where p.session_id = p_session and p.last_session_seq = v_seq - 1;
    if not found then
        perform spawn_session_fold(p_session);
    end if;

    perform pg_notify('spawn_events', v_id::text);

    return query select v_id, v_seq, v_at, true;
end $$;

create table if not exists spawn_commands (
    id              bigint generated by default as identity primary key,
    principal       text   not null,
    idempotency_key text   not null,
    agent_id        text   not null,
    session_id      text   not null,
    action          jsonb  not null,
    state           text   not null default 'pending',
    lease_worker    text,
    lease_attempt   integer not null default 0,
    lease_until_ms  bigint,
    succeeded       boolean,
    error           text,
    created_at_ms   bigint not null,
    finished_at_ms  bigint,
    unique (principal, idempotency_key)
);

create index if not exists spawn_commands_open
    on spawn_commands (session_id, id)
    where state <> 'finished';

create table if not exists spawn_grants (
    principal text not null,
    agent_id  text not null,
    primary key (principal, agent_id)
);

create or replace function spawn_submit(
    p_principal text,
    p_key       text,
    p_agent     text,
    p_session   text,
    p_action    jsonb
) returns table (out_id bigint) language plpgsql as $$
declare
    v_id bigint;
begin
    insert into spawn_commands
        (principal, idempotency_key, agent_id, session_id, action, state, created_at_ms)
    values
        (p_principal, p_key, p_agent, p_session, p_action, 'pending', spawn_now_ms())
    on conflict (principal, idempotency_key) do nothing
    returning spawn_commands.id into v_id;

    if v_id is null then
        select c.id into v_id
            from spawn_commands c
            where c.principal = p_principal and c.idempotency_key = p_key;
        return query select v_id;
        return;
    end if;

    perform spawn_append(
        p_agent, p_session, null, 'gateway', 'cmd_' || v_id || ':accepted',
        jsonb_build_object('name', 'command.accepted',
                           'detail', jsonb_build_object('command_id', v_id)));

    return query select v_id;
end $$;

create or replace function spawn_claim(
    p_worker text,
    p_ttl_ms bigint
) returns table (
    out_id      bigint,
    out_attempt integer,
    out_agent   text,
    out_session text,
    out_action  jsonb
) language sql as $$
    with candidate as (
        select c.id
        from spawn_commands c
        where c.state <> 'finished'
          and (c.lease_until_ms is null or c.lease_until_ms <= spawn_now_ms())
          and not exists (
              select 1 from spawn_commands o
              where o.session_id = c.session_id
                and o.state <> 'finished'
                and o.id < c.id
          )
        order by c.id
        for update skip locked
        limit 1
    )
    update spawn_commands c
    set lease_worker = p_worker,
        lease_attempt = c.lease_attempt + 1,
        lease_until_ms = spawn_now_ms() + p_ttl_ms
    from candidate
    where c.id = candidate.id
    returning c.id, c.lease_attempt, c.agent_id, c.session_id, c.action;
$$;

create or replace function spawn_finish(
    p_command   bigint,
    p_attempt   integer,
    p_succeeded boolean,
    p_error     text
) returns text language plpgsql as $$
declare
    v_state   text;
    v_attempt integer;
    v_agent   text;
    v_session text;
begin
    select c.state, c.lease_attempt, c.agent_id, c.session_id
        into v_state, v_attempt, v_agent, v_session
        from spawn_commands c
        where c.id = p_command
        for update;

    if v_state is null then
        return 'missing';
    end if;
    if v_state = 'finished' then
        return 'already';
    end if;
    if v_attempt <> p_attempt then
        return 'stale';
    end if;

    update spawn_commands c
        set state = 'finished',
            succeeded = p_succeeded,
            error = p_error,
            finished_at_ms = spawn_now_ms()
        where c.id = p_command;

    perform spawn_append(
        v_agent, v_session, null, 'gateway', 'cmd_' || p_command || ':finished',
        jsonb_build_object('name', 'command.finished',
            'detail', jsonb_build_object(
                'command_id', p_command,
                'succeeded', p_succeeded,
                'error', p_error)));

    return 'done';
end $$;

create or replace view agent_commands as
select c.id, c.agent_id, c.session_id, c.idempotency_key, c.action, c.created_at_ms
from spawn_commands c;

create or replace function spawn_gateway_insert() returns trigger
language plpgsql security definer as $$
declare
    v_id bigint;
begin
    if not exists (
        select 1 from spawn_grants g
        where g.principal = session_user::text
          and (g.agent_id = new.agent_id or g.agent_id = '*')
    ) then
        raise exception 'principal % has no grant for agent %', session_user, new.agent_id
            using errcode = '42501';
    end if;

    select s.out_id into v_id
        from spawn_submit(session_user::text, new.idempotency_key, new.agent_id, new.session_id, new.action) s;

    new.id := v_id;
    select c.created_at_ms into new.created_at_ms from spawn_commands c where c.id = v_id;
    return new;
end $$;

drop trigger if exists spawn_gateway_insert on agent_commands;
create trigger spawn_gateway_insert
    instead of insert on agent_commands
    for each row execute function spawn_gateway_insert();

create or replace view agent_state as
select
    p.session_id,
    p.agent_id,
    p.observation ->> 'state'      as state,
    p.observation ->> 'reason'     as reason,
    (p.observation ->> 'confidence')::float8 as confidence,
    (p.observation ->> 'based_on_seq')::bigint as based_on_seq,
    p.observation ->> 'judge'      as judge,
    p.observation_seq as session_seq,
    p.observation_at_ms as recorded_at_ms,
    p.observation_event_id as event_id,
    p.observation
from spawn_session_state p
where p.observation is not null;

create or replace view agent_timeline as
select
    e.session_id,
    e.session_seq,
    e.id,
    e.agent_id,
    e.execution_id,
    e.source,
    e.event_name,
    e.kind -> 'detail' as detail,
    e.recorded_at_ms
from spawn_events e
where e.source <> 'observer';

-- Judgements are read apart from the timeline: they describe the session
-- instead of being part of it.
create or replace view agent_judgements as
select
    e.session_id,
    e.session_seq,
    e.id as event_id,
    e.agent_id,
    e.kind -> 'detail' -> 'observation' ->> 'state'  as state,
    e.kind -> 'detail' -> 'observation' ->> 'reason' as reason,
    (e.kind -> 'detail' -> 'observation' ->> 'based_on_seq')::bigint as based_on_seq,
    e.kind -> 'detail' -> 'observation' as observation,
    e.recorded_at_ms
from spawn_events e
where e.event_name = 'observation.recorded';

create or replace view agent_tasks as
select
    c.id as command_id,
    c.agent_id,
    c.session_id,
    c.action ->> 'type' as action,
    c.state,
    c.lease_worker,
    c.lease_attempt,
    c.succeeded,
    c.error,
    c.created_at_ms,
    c.finished_at_ms,
    coalesce(c.action ->> 'prompt', c.action ->> 'text') as prompt
from spawn_commands c;

create or replace view agent_executions as
select
    s.session_id,
    s.agent_id,
    s.execution_id,
    s.kind -> 'detail' ->> 'engine'    as engine,
    s.kind -> 'detail' ->> 'terminal'  as terminal,
    s.kind -> 'detail' ->> 'workspace' as workspace,
    s.recorded_at_ms as started_at_ms,
    x.kind -> 'detail' ->> 'cause'     as cause,
    (x.kind -> 'detail' ->> 'exit_code')::integer as exit_code,
    x.recorded_at_ms as ended_at_ms,
    -- The runner reports an engine exit with the engine as source; the
    -- execution ends only when the Bridge writes its own end event.
    exists (
        select 1 from spawn_events r
        where r.event_name = 'execution.ended'
          and r.session_id = s.session_id
          and r.execution_id = s.execution_id
          and r.source <> 'bridge'
    ) as exit_reported,
    x.recorded_at_ms - s.recorded_at_ms as duration_ms,
    (s.kind -> 'detail' ->> 'command_id')::bigint as command_id
from spawn_events s
left join lateral (
    select e.kind, e.recorded_at_ms
    from spawn_events e
    where e.event_name = 'execution.ended'
      and e.session_id = s.session_id
      and e.execution_id = s.execution_id
      and e.source = 'bridge'
    order by e.id
    limit 1
) x on true
where s.event_name = 'execution.started';

create or replace view agent_artifacts as
select
    e.session_id,
    e.agent_id,
    e.execution_id,
    e.kind -> 'detail' -> 'artifact' ->> 'project'  as project,
    e.kind -> 'detail' -> 'artifact' ->> 'branch'   as branch,
    e.kind -> 'detail' -> 'artifact' ->> 'commit'   as commit_id,
    e.kind -> 'detail' ->> 'reason'                 as reason,
    e.session_seq,
    e.recorded_at_ms
from spawn_events e
where e.event_name = 'artifact.committed';

create or replace view agent_relations as
select
    e.session_id,
    e.agent_id,
    e.kind -> 'detail' ->> 'parent_session_id' as parent_session_id,
    e.recorded_at_ms
from spawn_events e
where e.event_name = 'session.linked';

-- One row per (session, ancestor). Depth 1 is the parent.
-- ponytail: the depth cap of 64 stops a link cycle; reject cycles at write
-- time if a deeper tree appears.
create or replace view agent_lineage as
with recursive parent as (
    select distinct on (r.session_id) r.session_id, r.agent_id, r.parent_session_id
    from agent_relations r
    order by r.session_id, r.recorded_at_ms desc
), chain (session_id, agent_id, ancestor_session_id, depth) as (
    select p.session_id, p.agent_id, p.parent_session_id, 1
    from parent p
    union all
    select c.session_id, c.agent_id, p.parent_session_id, c.depth + 1
    from chain c
    join parent p on p.session_id = c.ancestor_session_id
    where c.depth < 64
)
select session_id, agent_id, ancestor_session_id, depth from chain;

-- Events of one command: its gateway events and every event of the
-- execution it created.
create or replace view agent_task_events as
select
    coalesce((e.kind -> 'detail' ->> 'command_id')::bigint,
             (s.kind -> 'detail' ->> 'command_id')::bigint) as command_id,
    e.session_id,
    e.agent_id,
    e.session_seq,
    e.id as event_id,
    e.execution_id,
    e.event_name,
    e.recorded_at_ms
from spawn_events e
left join spawn_events s
    on s.event_name = 'execution.started'
   and s.session_id = e.session_id
   and s.execution_id = e.execution_id
where e.event_name in ('command.accepted', 'command.finished') or s.id is not null;

-- Tool calls started and not completed or failed, in executions the Bridge
-- has not ended.
create or replace view agent_open_tools as
select
    s.session_id,
    s.agent_id,
    s.execution_id,
    s.kind -> 'detail' ->> 'tool_use_id' as tool_use_id,
    s.kind -> 'detail' ->> 'tool_name'   as tool_name,
    s.session_seq,
    s.recorded_at_ms as started_at_ms
from spawn_events s
where s.event_name = 'tool.started'
  and not exists (
      select 1 from spawn_events c
      where c.session_id = s.session_id
        and c.event_name in ('tool.completed', 'tool.failed')
        and c.kind -> 'detail' ->> 'tool_use_id' = s.kind -> 'detail' ->> 'tool_use_id'
  )
  and not exists (
      select 1 from spawn_events x
      where x.session_id = s.session_id
        and x.event_name = 'execution.ended'
        and x.source = 'bridge'
        and x.execution_id = s.execution_id
  );

-- Position of the log per session. This is not judgement lag; see
-- docs/view-architecture.md section 4.1.
create or replace view agent_freshness as
select p.session_id, p.agent_id, p.last_session_seq, p.last_event_id,
       p.last_event_at_ms, p.event_count
from spawn_session_state p;

-- One row per session: the latest judgement and the latest execution.
create or replace view agent_status as
select
    p.session_id,
    p.agent_id,
    p.observation ->> 'state'  as state,
    p.observation ->> 'reason' as reason,
    p.observation_seq,
    p.last_session_seq,
    p.last_event_at_ms,
    x.execution_id,
    x.engine,
    x.started_at_ms,
    x.ended_at_ms,
    x.exit_reported,
    x.execution_id is not null and x.ended_at_ms is null as live
from spawn_session_state p
left join lateral (
    select a.execution_id, a.engine, a.started_at_ms, a.ended_at_ms, a.exit_reported
    from agent_executions a
    where a.session_id = p.session_id
    order by a.started_at_ms desc, a.execution_id desc
    limit 1
) x on true;

-- The raw tables, the projection and the views stay with the owner. Readers
-- go through the grant-filtered `spawn_read_*` functions below; the gateway
-- trigger runs as the owner and checks `session_user` against `spawn_grants`.
-- The revoke on the views also removes the public select of older schemas.
revoke all on spawn_events, spawn_commands, spawn_grants, spawn_session_state from public;
revoke select on agent_state, agent_status, agent_timeline, agent_judgements, agent_tasks,
    agent_task_events, agent_executions, agent_artifacts, agent_relations,
    agent_lineage, agent_open_tools, agent_freshness
    from public;
grant insert on agent_commands to public;

revoke execute on function spawn_append(text, text, text, text, text, jsonb) from public;
revoke execute on function spawn_session_fold(text) from public;
revoke execute on function spawn_submit(text, text, text, text, jsonb) from public;
revoke execute on function spawn_claim(text, bigint) from public;
revoke execute on function spawn_finish(bigint, integer, boolean, text) from public;

-- A security definer function must not resolve names through the caller's
-- search_path, or a caller's temporary table could stand in for
-- `spawn_grants`. Pin the schema the migration runs in, temp schema last.
do $$
begin
    execute format(
        'alter function spawn_gateway_insert() set search_path = %I, pg_temp',
        current_schema()
    );
end
$$;

-- Grant-filtered readers: `spawn_read_<view>()` for the views that list
-- sessions, `spawn_read_<view>(session_id)` for per-session views. Each
-- returns the rows whose agent `session_user` holds a grant for.
do $$
declare
    v_view text;
    v_filter constant text :=
        'exists (select 1 from spawn_grants g where g.principal = session_user::text'
        ' and g.agent_id in (r.agent_id, ''*''))';
begin
    foreach v_view in array array['state', 'status', 'tasks', 'relations', 'freshness'] loop
        execute format(
            'create or replace function spawn_read_%1$s() returns setof agent_%1$s'
            ' language sql stable security definer set search_path = %2$I, pg_temp'
            ' as $f$ select r.* from agent_%1$s r where %3$s $f$',
            v_view, current_schema(), v_filter);
    end loop;
    foreach v_view in array array['timeline', 'judgements', 'executions', 'artifacts',
                                  'task_events', 'lineage', 'open_tools'] loop
        execute format(
            'create or replace function spawn_read_%1$s(p_session text) returns setof agent_%1$s'
            ' language sql stable security definer set search_path = %2$I, pg_temp'
            ' as $f$ select r.* from agent_%1$s r where r.session_id = p_session and %3$s $f$',
            v_view, current_schema(), v_filter);
    end loop;
end
$$;
