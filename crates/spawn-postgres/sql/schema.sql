-- A grant either lets a principal read an agent's views (`read`) or also
-- submit commands for it (`all`). `agent_id` is an id, `*`, or a prefix
-- pattern such as `agent_worker_*`, so the supervisor can command every worker
-- without being able to command itself.
create table if not exists spawn_grants (
    principal text not null,
    agent_id  text not null,
    scope     text not null default 'all',
    primary key (principal, agent_id)
);

-- Every start migrates in place: a table made by an earlier schema keeps its
-- rows and gets each column added since, here, after its `create table`.
-- tests/upgrade.rs builds the first shape of every table and checks that a
-- migration over it matches a fresh schema.
alter table spawn_grants add column if not exists scope text not null default 'all';


create or replace function spawn_grant_matches(p_pattern text, p_agent text)
returns boolean language sql immutable as $$
    select p_pattern = '*'
        or p_pattern = p_agent
        or (right(p_pattern, 1) = '*'
            and left(p_agent, length(p_pattern) - 1) = left(p_pattern, length(p_pattern) - 1))
$$;

create or replace function spawn_submit(
    p_principal text,
    p_key       text,
    p_agent     text,
    p_session   text,
    p_action    jsonb
) returns table (out_id bigint) language plpgsql as $$
declare
    v_id bigint;
begin
    -- The id is taken under the append lock, which is held to commit:
    -- commands commit in id order, the order `spawn_claim` relies on.
    perform pg_advisory_xact_lock(1399957335);
    insert into spawn_commands
        (principal, idempotency_key, agent_id, session_id, action, state, created_at_ms)
    values
        (p_principal, p_key, p_agent, p_session, p_action, 'pending', spawn_now_ms())
    on conflict (principal, idempotency_key) do nothing
    returning spawn_commands.id into v_id;

    if v_id is null then
        select c.id into v_id
            from spawn_commands c
            where c.principal = p_principal and c.idempotency_key = p_key;
        return query select v_id;
        return;
    end if;

    perform spawn_append_trusted(
        p_agent, p_session, null, 'gateway', 'cmd_' || v_id || ':accepted',
        jsonb_build_object('name', 'command.accepted',
                           'detail', jsonb_build_object('command_id', v_id)));

    return query select v_id;
end $$;

-- The first version returned no principal.
drop function if exists spawn_claim(text, bigint);
create or replace function spawn_claim(
    p_worker text,
    p_ttl_ms bigint
) returns table (
    out_id        bigint,
    out_attempt   integer,
    out_agent     text,
    out_session   text,
    out_action    jsonb,
    out_principal text
) language sql as $$
    -- One command per session at a time: nothing earlier in the session
    -- may be unfinished, but an input that waits for its turn (the Bridge
    -- recorded its `command.step` `waiting`, keyed `cmd_<id>:waiting`): it
    -- holds nothing behind it. A stop, a discard or a resume behind it is
    -- handled at once, and an input behind it is claimed and kept behind it
    -- by the Bridge (typed after it, or refused while it waits). An
    -- unfinished input that does not wait still holds everything. "Earlier"
    -- is id order, which is commit order because `spawn_submit` takes its id
    -- under the append lock.
    with candidate as (
        select c.id
        from spawn_commands c
        where c.state <> 'finished'
          and (c.lease_until_ms is null or c.lease_until_ms <= spawn_now_ms())
          and not exists (
              select 1 from spawn_commands o
              where o.session_id = c.session_id
                and o.state <> 'finished'
                and o.id < c.id
                and not exists (
                    select 1 from spawn_events w
                    where w.session_id = o.session_id and w.source = 'bridge'
                      and w.source_event_id = 'cmd_' || o.id || ':waiting')
          )
        order by c.id
        for update skip locked
        limit 1
    )
    update spawn_commands c
    set lease_worker = p_worker,
        lease_attempt = c.lease_attempt + 1,
        lease_until_ms = spawn_now_ms() + p_ttl_ms
    from candidate
    where c.id = candidate.id
    returning c.id, c.lease_attempt, c.agent_id, c.session_id, c.action, c.principal;
$$;

-- Leave a claimed command unfinished and claimable again in `p_ms`: an
-- input that waits for its turn. A lease that is no longer this attempt's
-- changes nothing. Returns whether it released.
create or replace function spawn_release(
    p_command bigint,
    p_attempt integer,
    p_ms      bigint
) returns boolean language sql as $$
    update spawn_commands c
       set lease_until_ms = spawn_now_ms() + greatest(p_ms, 0)
     where c.id = p_command and c.state <> 'finished' and c.lease_attempt = p_attempt
    returning true;
$$;

create or replace function spawn_finish(
    p_command   bigint,
    p_attempt   integer,
    p_succeeded boolean,
    p_error     text
) returns text language plpgsql as $$
declare
    v_state   text;
    v_attempt integer;
    v_agent   text;
    v_session text;
begin
    select c.state, c.lease_attempt, c.agent_id, c.session_id
        into v_state, v_attempt, v_agent, v_session
        from spawn_commands c
        where c.id = p_command
        for update;

    if v_state is null then
        return 'missing';
    end if;
    if v_state = 'finished' then
        return 'already';
    end if;
    if v_attempt <> p_attempt then
        return 'stale';
    end if;

    update spawn_commands c
        set state = 'finished',
            succeeded = p_succeeded,
            error = p_error,
            finished_at_ms = spawn_now_ms()
        where c.id = p_command;

    perform spawn_append(
        v_agent, v_session, null, 'gateway', 'cmd_' || p_command || ':finished',
        jsonb_build_object('name', 'command.finished',
            'detail', jsonb_build_object(
                'command_id', p_command,
                'succeeded', p_succeeded,
                'error', p_error)));

    return 'done';
end $$;

create or replace view agent_commands as
select c.id, c.agent_id, c.session_id, c.idempotency_key, c.action, c.created_at_ms
from spawn_commands c;

create or replace function spawn_gateway_insert() returns trigger
language plpgsql security definer as $$
declare
    v_id bigint;
begin
    if not exists (
        select 1 from spawn_grants g
        where g.principal = spawn_principal()
          and g.scope = 'all'
          and spawn_grant_matches(g.agent_id, new.agent_id)
    ) then
        raise exception 'principal % has no grant for agent %', session_user, new.agent_id
            using errcode = '42501';
    end if;
    -- A session belongs to the agent that first used it: a grant for one
    -- agent must not reach another agent's session (the Bridge acts on the
    -- session, not the agent). This early answer names the pair; the append
    -- in `spawn_submit` is what holds it when two first submissions race.
    if exists (select 1 from spawn_agent_sessions s
                where s.session_id = new.session_id and s.agent_id <> new.agent_id) then
        raise exception 'session % belongs to another agent than %', new.session_id, new.agent_id
            using errcode = '42501';
    end if;
    if exists (select 1 from spawn_agent_sessions s
                where s.agent_id = new.agent_id and s.session_id <> new.session_id) then
        raise exception 'agent % has another session than %', new.agent_id, new.session_id
            using errcode = '42501';
    end if;

    select s.out_id into v_id
        from spawn_submit(spawn_principal(), new.idempotency_key, new.agent_id, new.session_id,
                          new.action) s;

    new.id := v_id;
    select c.created_at_ms into new.created_at_ms from spawn_commands c where c.id = v_id;
    return new;
end $$;

