-- The owner moved a source's main forward outside the gate (a deploy): the
-- missions whose baseline is `p_from` take `p_to` instead of halting. The
-- caller checks that `p_to` descends from `p_from`; returns how many missions
-- moved. A mission without a baseline yet, or halted, is left alone.
create or replace function spawn_source_moved(p_source text, p_from text, p_to text)
returns integer language plpgsql security definer as $$
declare
    v_count integer;
begin
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception 'only the owner moves a source outside the gate' using errcode = '42501';
    end if;
    select count(*) into v_count from mission_missions
     where sources ->> 0 = p_source and baseline = p_from;
    if v_count > 0 then
        perform spawn_control_record(jsonb_build_object(
            'type', 'source.moved', 'source', p_source, 'from', p_from, 'to', p_to));
    end if;
    return v_count;
end $$;

-- The integrator's records (`spawn integrate`, owner only): gate verdicts,
-- landings, aborts over budget, and halts.
create or replace function spawn_integrator_record(p_record jsonb)
returns bigint language plpgsql security definer as $$
begin
    -- Check and record under the append lock, so no other change interleaves.
    perform pg_advisory_xact_lock(1399957335);
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception '% may not record landings', session_user using errcode = '42501';
    end if;
    if p_record ->> 'type' not in ('task.gated', 'task.landed', 'task.aborted', 'mission.halted') then
        raise exception 'the integrator does not record %', p_record ->> 'type';
    end if;
    if p_record ->> 'type' = 'task.gated'
       and p_record ->> 'verdict' not in ('accepted', 'rejected', 'conflict', 'aborted', 'stale') then
        raise exception 'unknown gate verdict %', p_record ->> 'verdict';
    end if;
    -- The gate runs for minutes: the task may have been closed meanwhile.
    -- A verdict only moves work that is still waiting for it.
    if p_record ->> 'type' like 'task.%' and not exists (
        select 1 from mission_tasks
         where id = (p_record ->> 'id')::bigint
           and state = any (case p_record ->> 'type'
                              when 'task.landed' then array['landing']
                              when 'task.aborted' then array['delivered']
                              else array['reported', 'accepted', 'landing'] end)) then
        raise exception 'task % is not waiting for %', p_record ->> 'id', p_record ->> 'type';
    end if;
    return spawn_control_record(p_record);
end $$;

-- The integrator's hold on one landing (owner only): taken right before its
-- compare-and-swap push and released after it records what the push did
-- (spawn_landing_release). Dropping a mission waits for the hold, so a push
-- never lands work of a mission dropped meanwhile. True when the task is
-- still landing for a mission that is not dropped. A landing task of a
-- dropped mission (a fold from before drops cancelled landings) is
-- recorded cancelled instead.
create or replace function spawn_landing_hold(p_task bigint)
returns boolean language plpgsql security definer as $$
begin
    if spawn_mission_caller() is distinct from 'owner' then
        raise exception '% may not land work', session_user using errcode = '42501';
    end if;
    perform pg_advisory_lock(1399957337);
    if exists (select 1 from mission_tasks k join mission_missions m on m.id = k.mission_id
                where k.id = p_task and k.state = 'landing' and m.state <> 'dropped') then
        return true;
    end if;
    perform pg_advisory_xact_lock(1399957335);
    if exists (select 1 from mission_tasks k join mission_missions m on m.id = k.mission_id
                where k.id = p_task and k.state = 'landing' and m.state = 'dropped') then
        perform spawn_control_record(jsonb_build_object('type', 'task.cancelled', 'id', p_task));
    end if;
    perform pg_advisory_unlock(1399957337);
    return false;
end $$;

create or replace function spawn_landing_release()
returns void language plpgsql security definer as $$
begin
    perform pg_advisory_unlock(1399957337);
end $$;

-- A task's records in the control stream, found without reading the rest.
create index if not exists spawn_events_control_record
    on spawn_events ((kind -> 'detail' -> 'record' ->> 'id'), session_seq)
    where session_id = 'session_control' and event_name = 'control.recorded';

-- A task's stages, oldest first: `[{stage, verdict?, at_ms, took_ms?}]`.
-- `stage` is the record type without `task.`; `verdict` is a gate's verdict
-- or a review's (`accepted`, `rejected`); `took_ms` is the time since the
-- task's previous record (none on the first). Runs as the owner, so the
-- supervisor's login, which may not read `spawn_events`, reads it too.
create or replace function spawn_task_stages(p_task bigint)
returns jsonb language sql stable security definer as $$
    select coalesce(jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
               'stage', substr(s.type, 6), 'verdict', s.verdict, 'at_ms', s.at_ms,
               'took_ms', s.at_ms - s.previous_ms)) order by s.seq), '[]'::jsonb)
      from (select e.session_seq as seq, r.record ->> 'type' as type,
                   case r.record ->> 'type'
                     when 'task.gated' then r.record ->> 'verdict'
                     when 'task.reviewed' then
                       case when (r.record ->> 'accepted')::boolean then 'accepted'
                            else 'rejected' end
                   end as verdict,
                   e.recorded_at_ms as at_ms,
                   lag(e.recorded_at_ms) over (order by e.session_seq) as previous_ms
              from spawn_events e
             cross join lateral (select e.kind -> 'detail' -> 'record' as record) r
             where e.session_id = 'session_control' and e.event_name = 'control.recorded'
               and (e.kind -> 'detail' -> 'record' ->> 'id') = p_task::text
               and r.record ->> 'type' like 'task.%') s
$$;

-- A database from before the control stream has rows and no records. Each
-- row becomes one `legacy.imported` record, once.
do $$
declare
    v_row record;
begin
    perform pg_advisory_xact_lock(1399957335);
    if exists (select 1 from spawn_events where session_id = 'session_control')
       or not exists (select 1 from mission_missions union all select 1 from mission_residents) then
        return;
    end if;
    create temporary table spawn_legacy_rows on commit drop as
        select 1 as part, 'mission_missions' as name, to_jsonb(m) as row, lpad(m.id::text, 20, '0') as ord
          from mission_missions m
        union all
        select 2, 'mission_residents', to_jsonb(r), lpad(r.created_at_ms::text, 20, '0') || r.name
          from mission_residents r
        union all
        select 3, 'mission_tasks', to_jsonb(t), lpad(t.id::text, 20, '0')
          from mission_tasks t;
    delete from mission_tasks;
    delete from mission_residents;
    delete from mission_missions;
    for v_row in
        select name, row from spawn_legacy_rows
         order by part, ord
    loop
        perform spawn_control_record(jsonb_build_object(
            'type', 'legacy.imported', 'table', v_row.name, 'row', v_row.row));
    end loop;
end
$$;

