-- The first shape of every table the schema has made, each as the commit
-- that introduced it created it: spawn_events, spawn_commands and
-- spawn_grants (2d1eddb), spawn_session_state (0a7c637), the retired RSI
-- controller's rsi_* (ed108b4), and mission_* (a26b913). A database from
-- any of those installs has at least these columns; tests/upgrade.rs
-- migrates over them.

create table spawn_events (
    id              bigint generated by default as identity primary key,
    agent_id        text   not null,
    session_id      text   not null,
    execution_id    text,
    source          text   not null,
    source_event_id text,
    kind            jsonb  not null,
    session_seq     bigint not null,
    recorded_at_ms  bigint not null,
    event_name      text generated always as (kind ->> 'name') stored
);

create table spawn_commands (
    id              bigint generated by default as identity primary key,
    principal       text   not null,
    idempotency_key text   not null,
    agent_id        text   not null,
    session_id      text   not null,
    action          jsonb  not null,
    state           text   not null default 'pending',
    lease_worker    text,
    lease_attempt   integer not null default 0,
    lease_until_ms  bigint,
    succeeded       boolean,
    error           text,
    created_at_ms   bigint not null,
    finished_at_ms  bigint,
    unique (principal, idempotency_key)
);

create table spawn_grants (
    principal text not null,
    agent_id  text not null,
    primary key (principal, agent_id)
);

create table spawn_session_state (
    session_id           text   primary key,
    agent_id             text   not null,
    last_session_seq     bigint not null,
    last_event_id        bigint not null,
    last_event_at_ms     bigint not null,
    event_count          bigint not null,
    observation          jsonb,
    observation_seq      bigint,
    observation_event_id bigint,
    observation_at_ms    bigint
);

create table rsi_state (
    id                   integer primary key check (id = 1),
    baseline_commit      text   not null,
    iteration            integer not null default 0,
    consecutive_rejected integer not null default 0
);

create table rsi_iterations (
    iteration     integer primary key,
    task_id       integer not null,
    phase         text    not null,
    agent_id      text    not null,
    session_id    text    not null,
    command_id    bigint,
    patch         text,
    candidate     text,
    note          text,
    updated_at_ms bigint  not null
);

create table rsi_attempts (
    task_id       integer not null,
    attempt       integer not null,
    iteration     integer not null,
    diff          text,
    gate_log      text,
    classifier    text,
    accept_ok     boolean,
    created_at_ms bigint  not null,
    primary key (task_id, attempt)
);

create table mission_missions (
    id            bigint generated by default as identity primary key,
    text          text   not null,
    origin        text   not null,
    sources       jsonb  not null default '[]'::jsonb,
    state         text   not null default 'open'
                  check (state in ('open', 'active', 'done', 'dropped')),
    summary       text,
    created_at_ms bigint not null,
    updated_at_ms bigint not null
);

create table mission_residents (
    name          text   primary key check (name ~ '^[a-z][a-z0-9_]{0,30}$'),
    agent_id      text   not null unique,
    session_id    text   not null unique,
    charter       text   not null,
    state         text   not null default 'proposed'
                  check (state in ('proposed', 'approved', 'retired')),
    proposed_by   text   not null,
    approved_by   text,
    created_at_ms bigint not null,
    updated_at_ms bigint not null
);

create table mission_tasks (
    id            bigint generated by default as identity primary key,
    mission_id    bigint not null references mission_missions (id),
    kind          text   not null check (kind in ('resident', 'ephemeral')),
    agent_id      text   not null,
    session_id    text   not null,
    brief         text   not null,
    state         text   not null default 'assigned'
                  check (state in ('assigned', 'delivered', 'reported', 'revise',
                                   'accepted', 'cancelled')),
    revisions     integer not null default 0,
    review_note   text,
    command_id    bigint,
    report        text,
    created_by    text   not null,
    created_at_ms bigint not null,
    updated_at_ms bigint not null
);
